#!/usr/bin/env python3
"""Generate the asyncio Python SDK layer from the synchronous one ("unasync").

Inputs : sdks/python/src/nova_sdk/http.py, sdks/python/src/nova_sdk/resources/*.py
Outputs: sdks/python/src/nova_sdk/aio/http.py
         sdks/python/src/nova_sdk/aio/resources/*.py   (do not edit by hand)

The synchronous code is the single source of truth. Every public resource method
becomes a coroutine and every transport / sub-resource call is awaited.

Usage:
    scripts/gen_python_async.py          # (re)write files
    scripts/gen_python_async.py --check  # exit 1 if generated files are stale
"""

from __future__ import annotations

import argparse
import ast
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG = ROOT / "sdks" / "python" / "src" / "nova_sdk"
AIO = PKG / "aio"
HEADER = (
    "# AUTO-GENERATED by scripts/gen_python_async.py from {src}.\n"
    "# Do not edit by hand; edit the synchronous source and regenerate.\n"
)


def segment(src: str, node: ast.AST) -> str:
    lines = src.splitlines()
    start = node.lineno - 1
    if getattr(node, "decorator_list", None):
        start = node.decorator_list[0].lineno - 1
    return "\n".join(lines[start : node.end_lineno])


# --------------------------------------------------------------------- transport
def gen_transport() -> str:
    src = (PKG / "http.py").read_text()
    tree = ast.parse(src)
    cls = next(
        n
        for n in tree.body
        if isinstance(n, ast.ClassDef) and n.name == "HTTPTransport"
    )
    methods = {
        n.name: segment(src, n) for n in cls.body if isinstance(n, ast.FunctionDef)
    }
    body = []
    for name in ("_send_request", "request_raw", "request"):
        text = methods[name]
        text = re.sub(r"^    def ", "    async def ", text, count=1)
        text = text.replace("self._client.request(", "await self._client.request(")
        text = text.replace("time.sleep(", "await asyncio.sleep(")
        text = text.replace("self._send_request(", "await self._send_request(")
        text = text.replace(
            "return self._parse_success_response", "return self._parse_success_response"
        )
        body.append(text)
    return (
        HEADER.format(src="nova_sdk/http.py")
        + '''"""Asynchronous HTTP transport for the Nova SDK."""

from __future__ import annotations

import asyncio
import logging
from collections.abc import Mapping
from typing import Any

import httpx

from nova_sdk.config import NovaConfig
from nova_sdk.exceptions import (
    NovaConnectionError,
    NovaError,
    NovaTimeoutError,
)
from nova_sdk.http import IDEMPOTENT_METHODS, TransportCore
from nova_sdk.models import ApiResponse

logger = logging.getLogger("nova_sdk.http")


class AsyncHTTPTransport(TransportCore):
    """Manages low-level asynchronous HTTP communication with the Nova REST API."""

    def __init__(
        self,
        config: NovaConfig,
        *,
        client: httpx.AsyncClient | None = None,
    ) -> None:
        self.config = config
        self._custom_client = client is not None
        self._client = client or httpx.AsyncClient(
            timeout=httpx.Timeout(config.timeout),
            verify=config.verify_ssl,
            follow_redirects=False,  # Prevent credential leakage across redirect hops
        )

    @property
    def is_closed(self) -> bool:
        return self._client.is_closed

    async def aclose(self) -> None:
        """Close the underlying HTTP client session."""
        if not self._custom_client and not self._client.is_closed:
            await self._client.aclose()

    async def __aenter__(self) -> AsyncHTTPTransport:
        return self

    async def __aexit__(self, exc_type: Any, exc_val: Any, exc_tb: Any) -> None:
        await self.aclose()

'''
        + "\n\n".join(body)
        + "\n"
    )


# --------------------------------------------------------------------- resources
ASYNC_TYPE_IMPORTS = [
    ("from nova_sdk.resources.base import BaseResource", "from nova_sdk.aio.resources.base import BaseResource"),
    (
        "from nova_sdk.client import NovaClient",
        "from nova_sdk.aio.client import AsyncNovaClient",
    ),
    (
        "from nova_sdk.http import HTTPTransport",
        "from nova_sdk.aio.http import AsyncHTTPTransport",
    ),
]


def gen_resource(path: Path) -> str:
    src = path.read_text()
    tree = ast.parse(src)
    out = src
    edits: list[tuple[int, int, str]] = []  # (start_line, end_line, replacement)

    for cls in [n for n in tree.body if isinstance(n, ast.ClassDef)]:
        sub_attrs: set[str] = set()
        init = next(
            (
                n
                for n in cls.body
                if isinstance(n, ast.FunctionDef) and n.name == "__init__"
            ),
            None,
        )
        if init:
            for node in ast.walk(init):
                if (
                    isinstance(node, ast.Assign)
                    and isinstance(node.targets[0], ast.Attribute)
                    and isinstance(node.value, ast.Call)
                    and isinstance(node.value.func, ast.Name)
                    and node.value.func.id.endswith("Resource")
                ):
                    sub_attrs.add(node.targets[0].attr)
        public = {
            n.name
            for n in cls.body
            if isinstance(n, ast.FunctionDef)
            and not n.name.startswith("_")
            and not any(
                isinstance(d, ast.Name) and d.id == "staticmethod"
                for d in n.decorator_list
            )
        }
        for fn in [
            n for n in cls.body if isinstance(n, ast.FunctionDef) and n.name in public
        ]:
            text = segment(src, fn)
            new = re.sub(r"^    def ", "    async def ", text, count=1, flags=re.M)
            new = re.sub(
                r"(?<!await )self\._transport\.(request_raw|request)\(",
                r"await self._transport.\1(",
                new,
            )
            for attr in sub_attrs:
                new = re.sub(
                    rf"(?<!await )self\.{attr}\.(\w+)\(", rf"await self.{attr}.\1(", new
                )
            for name in public:
                new = re.sub(rf"(?<!await )self\.{name}\(", f"await self.{name}(", new)
            start = fn.decorator_list[0].lineno if fn.decorator_list else fn.lineno
            edits.append((start, fn.end_lineno, new))

    lines = out.splitlines()
    for start, end, new in sorted(edits, reverse=True):
        lines[start - 1 : end] = new.splitlines()
    out = "\n".join(lines) + "\n"
    for old, new in ASYNC_TYPE_IMPORTS:
        out = out.replace(old, new)
    out = (
        re.sub(r"\bNovaClient\b(?!\()", "AsyncNovaClient", out)
        if "AsyncNovaClient" in out
        else out
    )
    out = out.replace("transport: HTTPTransport", "transport: AsyncHTTPTransport")
    out = out.replace("self._client = client\n", "self._client = client\n")
    return HEADER.format(src=f"nova_sdk/resources/{path.name}") + out


def format_code(text: str, path: Path) -> str:
    """Format with ruff (project config) so generated output matches committed files."""
    ruff = shutil.which("ruff")
    if ruff is None:
        sys.exit("ruff is required to format generated code (pip install ruff).")
    cwd = ROOT / "sdks" / "python"
    # Sort imports first (the transformed imports change their order), then format.
    sorted_text = subprocess.run(
        [ruff, "check", "--select", "I", "--fix", "--exit-zero", "--quiet", "--stdin-filename", str(path), "-"],
        input=text, capture_output=True, text=True, cwd=cwd, check=True,
    ).stdout
    result = subprocess.run(
        [ruff, "format", "--stdin-filename", str(path), "-"],
        input=sorted_text, capture_output=True, text=True, cwd=cwd, check=True,
    )
    return result.stdout


def render_all() -> dict[Path, str]:
    files = {AIO / "http.py": gen_transport()}
    res_dir = PKG / "resources"
    for path in sorted(res_dir.glob("*.py")):
        if path.name in ("__init__.py", "base.py", "_files.py"):
            continue
        files[AIO / "resources" / path.name] = gen_resource(path)
    return {path: format_code(text, path) for path, text in files.items()}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files = render_all()
    stale = []
    for path, text in files.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if args.check:
        if stale:
            for p in stale:
                print(f"stale: {p.relative_to(ROOT)}")
            print("Run scripts/gen_python_async.py (then ruff format) to regenerate.")
            return 1
        print("Async SDK layer is up to date.")
        return 0
    print(f"Wrote {len(files)} files under {AIO.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
